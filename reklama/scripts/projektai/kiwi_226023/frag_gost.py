def prep_all(org, out):
    """viena originalo kopija, iš kurios visuose 3 puslapiuose pašalinti Arial užrašai"""
    import sys, os
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
    import gost_frag as GF
    import pymupdf as fitz
    d = fitz.open(org)
    for pno, rr in REDACT.items():
        pg = d[pno]
        for r in rr:
            pg.add_redact_annot(fitz.Rect(r[0] - 0.6, r[1] - 0.6, r[2] + 0.6, r[3] + 0.6), fill=False)
        pg.apply_redactions(images=fitz.PDF_REDACT_IMAGE_NONE, graphics=fitz.PDF_REDACT_LINE_ART_REMOVE_IF_COVERED,
                            text=fitz.PDF_REDACT_TEXT_REMOVE)
    d.save(out, garbage=3, deflate=True)
    return out
